namespace {

// The four cmov pairs, high byte lane to low: (shift, threshold, add when
// below, add when at or above). Written as data because that is what the
// disassembly is — four identical compare/conditional-add pairs, one per byte
// of the index word. Every wrapped index stays inside 0..251, so the unaligned
// four-byte read never runs off the table.
struct Lane {
    u32 shift, thresh;
    i32 below, atOrAbove;
};
constexpr Lane kLanes[4] = {
    {24, 4, 184, -4},
    {16, 12, 200, -12},
    {8, 24, 212, -24},
    {0, 28, 216, -28},
};
constexpr u32 kRotates[4] = {1, 2, 3, 0};

u32 Rotl32(u32 v, u32 n) {
    return n == 0 ? v : ((v << n) | (v >> (32 - n)));
}

/// A little-endian u32 at BYTE offset `off` of the table.
u32 TableWord(u32 off) {
    u32 v = 0;
    std::memcpy(&v, kRngTable.data() + off, sizeof(v));
    return v;
}

} // namespace

u32 Rng::NextU32() {
    u32 wrapped[4];
    for (i32 i = 0; i < 4; ++i) {
        const Lane& L = kLanes[i];
        const u32 b = (idx4_ >> L.shift) & 0xFFu;
        wrapped[i] = static_cast<u32>(static_cast<i32>(b) +
                                      (b < L.thresh ? L.below : L.atOrAbove));
    }
    u32 mix = 0;
    for (i32 i = 0; i < 4; ++i)
        mix ^= Rotl32(TableWord(wrapped[i]), kRotates[i]);
    acc_ += mix;
    idx4_ = (wrapped[0] << 24) | (wrapped[1] << 16) | (wrapped[2] << 8) | wrapped[3];
    return acc_;
}

f32 Rng::RangeF(f32 a, f32 b) {
    const f32 span = b - a; // subss BEFORE the draw — the state advances after.
    const u32 next = NextU32();
    const f32 mant = std::bit_cast<f32>((next & 0x7FFFFFu) | 0x3F800000u);
    const f32 unit = mant + (-1.0f); // addss with the -1.0f at 0x103C472BC
    return a + (unit * span);
}

u32 Rng::RangeInt(u32 lo, u32 hi) {
    const u32 span = hi - lo; // 32-bit sub; hi is EXCLUSIVE.
    const u32 next = NextU32();
    return lo + static_cast<u32>((static_cast<u64>(next) * span) >> 32);
}

